import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {PreviewEngine} from '../sdk/browser/engine.mjs';
import {PreviewDisplay} from '../sdk/browser/display.mjs';
import {shownControls} from '../sdk/browser/controls.mjs';
const module=new WebAssembly.Module(readFileSync(process.argv[2]));
const engine=new PreviewEngine(module,44100,Array(8).fill(0));
const display=new PreviewDisplay(module);
assert.equal(engine.audioWords,256); assert.equal(display.api.opxy_display_abi(),5);
engine.noteOn(60);engine.render(new Float32Array(64));
const snapshot=engine.takeAudio();
assert.equal(snapshot.count,256);assert.equal(snapshot.words[255],0x1020313f);
assert.deepEqual(engine.takeAudio().words,snapshot.words,'Persistent snapshots never clear producer values');
assert.equal(engine.takeAudio(1).words[255],0,'Track isolation');
const controls=shownControls(Array(8).fill(0),[0,1,2,3]);
display.tick(controls,17,1,0,false,null,null,snapshot);
assert.equal(display.audioResetRequested(),true);
const pending=engine.takeAudio(0,true);assert.ok(pending.requested);assert.equal(pending.applied,0);
display.tick(controls,17,2,0,false,null,null,pending);assert.equal(display.audioResetRequested(),false);
engine.render(new Float32Array(64));
const applied=engine.takeAudio();assert.equal(applied.applied,pending.requested);
display.tick(controls,17,3,0,false,null,null,applied);assert.equal(display.audioResetRequested(),true);
assert.throws(()=>display.tick(controls,17,4,0,false,null,null,{...applied,words:applied.words.slice(1)}),/telemetry/);
assert.throws(()=>engine.takeAudio(8),/track/);
console.log('PASS: ABI4 full256-word persistent snapshot, track isolation, bounded metadata and reset request/apply handshake.');
