const module=new WebAssembly.Module(readFileSync(process.argv[2]));
const display=new PreviewDisplay(module);
const input=shownControls(Array(8).fill(0),[0,1,2,3]);
const tick=(track=0)=>display.tick(input,17,0,track,false,null,null,{count:0,words:Array(16).fill(0)});
assert.equal(tick()[5],0,'real idle baseline before first interaction');
assert.equal(display.controlInteraction(0,1,1,100,{type:'input',isTrusted:false}),false);
assert.equal(tick()[5],0,'synthetic input/automation creates no serial');
assert.equal(display.controlInteraction(0,1,1,100,{type:'keydown',key:'End',isTrusted:true}),true);
assert.equal(tick()[5],1);assert.equal(tick()[6],100);
display.controlInteraction(0,1,1,100,{type:'keydown',key:'End',isTrusted:true});
assert.equal(tick()[5],2,'clamped edit advances serial');
display.controlInteraction(0,2,6,200,{type:'pointerdown',isTrusted:true});
assert.equal(tick()[5],3);assert.equal(tick()[6],200);assert.equal(tick()[13],2);assert.equal(tick()[14],6);
display.controlInteraction(1,0,0,300,{type:'input',isTrusted:true});
assert.equal(tick(1)[5],4);assert.equal(tick()[5],3,'tracks retain their ordered last event');
assert.throws(()=>display.controlInteraction(0,4,0,1,{type:'input',isTrusted:true}),/physical/);
assert.equal(tick()[5],3,'invalid event is atomic');
assert.equal(display.api.opxy_control_event(0,0,0,-1),0);assert.equal(tick()[5],3);
