import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {PreviewEngine} from '../sdk/browser/engine.mjs';
import {PreviewDisplay} from '../sdk/browser/display.mjs';
import {shownControls} from '../sdk/browser/controls.mjs';
const module=new WebAssembly.Module(readFileSync(process.argv[2]));
const audio=new PreviewEngine(module,44100,Array(8).fill(0));const display=new PreviewDisplay(module);
audio.noteOn(60);audio.render(new Float32Array(128));
const first=audio.takeAudio();assert.equal(first.count,60);
assert.deepEqual(first.words.slice(0,24),Array.from({length:24},(_,i)=>2*(i+1)));
const repeat=audio.takeAudio();assert.deepEqual(repeat.words.slice(0,24),Array(24).fill(0));
assert.deepEqual(repeat.words.slice(24),first.words.slice(24));
display.tick(shownControls(Array(8).fill(0),[0,1,2,3]),17,1,0,false,null,null,first);
assert.ok(display.audioResetRequested());assert.equal(display.audioResetTarget(),0xfedcba98);
const pending=audio.takeAudio(0,true,display.audioResetTarget());assert.ok(pending.requested);
assert.throws(()=>audio.takeAudio(0,true,0),/target/);assert.throws(()=>audio.takeAudio(0,true,0x100000000),/target/);
audio.render(new Float32Array(64));const applied=audio.takeAudio();
assert.equal(applied.applied,pending.requested);assert.equal(applied.words[59],0xfedcba98);
assert.deepEqual(applied.words.slice(0,24),Array.from({length:24},(_,i)=>i+1));
console.log('PASS: actual WASM24 independent accumulator lanes and exact u32 targeted reset.');
