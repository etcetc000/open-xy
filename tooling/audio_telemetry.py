"""A synth's audio snapshots for its own screen (docs/display.md#audio-snapshots).

audioWords alone gives a browser preview its snapshot; the device needs the native
transport (audioTransport), the profile's 'telemetry' service. Nothing here applies to
a machine that declares neither.
"""
from pathlib import Path


def display(definition):
    return definition['resources'].get('display', {})


def words(definition):
    return display(definition).get('audioWords', 0)


def enabled(definition):
    """Whether the machine uses the native transport."""
    return bool(display(definition).get('audioTransport'))


def wide(definition):
    """Whether its screen takes draw::TelemetryInput: more than 16 words, or the reset handshake."""
    d = display(definition)
    return enabled(definition) and (d.get('audioWords', 0) > 16 or bool(d.get('audioReset')))


def capacity(definition):
    return 256 if wide(definition) else 16


def input_type(definition):
    return 'TelemetryInput' if wide(definition) else 'AudioInput' if words(definition) else 'Input'


def users(machines):
    return [m for m in machines if m.kind == 'synth' and enabled(m.definition)]


def generate_registry(directory, machines):
    """Which engines own a transport bank, and each one's declared shape (audio_transport_native.hpp)."""
    selected = users(machines)
    lines = ['// Generated by the SDK: the selected synths with audio snapshots on the device.',
             '#include "audio_transport_native.hpp"',
             'namespace opxy { namespace platform { namespace telemetry {']
    for m in selected:
        lines.append(f'extern "C" wire::Bank* {m.prefix}_audio_bank(u32) __asm__("{m.prefix}_audio_bank");')
    lines += ['wire::Bank* resolve_bank(void*, wire::u16 engine, wire::u8 track) {',
              '    if (track >= 8 || audio_track_engine(track) != engine) return nullptr;',
              '    switch (engine) {']
    lines += [f'    case {m.identity["engine"]}: return {m.prefix}_audio_bank(track);' for m in selected]
    lines += ['    default: return nullptr;', '    }', '}',
              'bool configuration(u32 engine, u32& words, u32& mode, bool& reset, u32& prefix) {',
              '    switch (engine) {']
    for m in selected:
        d = display(m.definition)
        lines.append(f'    case {m.identity["engine"]}: words = {d["audioWords"]}; mode = {d["audioMode"]}; '
                     f'reset = {str(bool(d.get("audioReset"))).lower()}; prefix = {d.get("audioAccumulators", 1)}; '
                     'return true;')
    lines += ['    default: return false;', '    }', '}', '}}}']
    path = Path(directory) / 'telemetry_registry.cpp'
    path.write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
    return path
