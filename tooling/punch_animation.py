"""Punch-in flip-dot animations: a PNG strip of 40 x 18 frames to C++ frame data.

Frames sit side by side, left to right; a pixel at least half as bright as
white lights its dot. Reads 8-bit non-interlaced greyscale, RGB, palette and
alpha PNGs with the standard library only.

    python -m tooling.punch_animation rise=rise.png fall=fall.png > animations.hpp
"""
import argparse
import re
import struct
import sys
import zlib
from pathlib import Path

from .formats import require

COLUMNS, ROWS = 40, 18
FRAME_BYTES = COLUMNS * ROWS // 8
MAX_FRAMES = 255
NAME = re.compile(r'[a-z][a-z0-9_]{0,31}')
CHANNELS = {0: 1, 2: 3, 3: 1, 4: 2, 6: 4}


def read_png(data):
    """(width, height, rows of (r, g, b, a) tuples) of a supported PNG."""
    require(data[:8] == b'\x89PNG\r\n\x1a\n', 'Not a PNG')
    at, header, palette, compressed = 8, None, None, b''
    while at < len(data):
        require(at + 8 <= len(data), 'Truncated PNG')
        length, kind = struct.unpack('>I4s', data[at:at + 8])
        body = data[at + 8:at + 8 + length]
        require(len(body) == length, 'Truncated PNG')
        if kind == b'IHDR':
            header = struct.unpack('>IIBBBBB', body)
        elif kind == b'PLTE':
            palette = [tuple(body[i:i + 3]) for i in range(0, len(body), 3)]
        elif kind == b'IDAT':
            compressed += body
        elif kind == b'IEND':
            break
        at += 12 + length
    require(header is not None, 'PNG without a header')
    width, height, depth, color, _compression, _filter, interlace = header
    require(depth == 8 and color in CHANNELS and interlace == 0,
            'Use an 8-bit, non-interlaced PNG')
    require(color != 3 or palette, 'Palette PNG without a palette')
    channels = CHANNELS[color]
    stride = width * channels
    raw = zlib.decompress(compressed)
    require(len(raw) == height * (stride + 1), 'Unexpected PNG data size')
    rows, previous = [], bytearray(stride)
    for y in range(height):
        kind = raw[y * (stride + 1)]
        line = bytearray(raw[y * (stride + 1) + 1:(y + 1) * (stride + 1)])
        for x in range(stride):
            left = line[x - channels] if x >= channels else 0
            up = previous[x]
            corner = previous[x - channels] if x >= channels else 0
            if kind == 1:
                line[x] = (line[x] + left) & 255
            elif kind == 2:
                line[x] = (line[x] + up) & 255
            elif kind == 3:
                line[x] = (line[x] + (left + up) // 2) & 255
            elif kind == 4:
                p = left + up - corner
                pa, pb, pc = abs(p - left), abs(p - up), abs(p - corner)
                line[x] = (line[x] + (left if pa <= pb and pa <= pc else up if pb <= pc else corner)) & 255
            else:
                require(kind == 0, 'Unknown PNG filter')
        pixels = []
        for x in range(width):
            v = line[x * channels:(x + 1) * channels]
            if color == 0:
                pixels.append((v[0], v[0], v[0], 255))
            elif color == 2:
                pixels.append((v[0], v[1], v[2], 255))
            elif color == 3:
                require(v[0] < len(palette), 'Palette index out of range')
                pixels.append((*palette[v[0]], 255))
            elif color == 4:
                pixels.append((v[0], v[0], v[0], v[1]))
            else:
                pixels.append(tuple(v))
        rows.append(pixels)
        previous = line
    return width, height, rows


def frames(data):
    """The strip's frames, each FRAME_BYTES bytes: row by row, least significant bit first."""
    width, height, rows = read_png(data)
    require(height == ROWS and width % COLUMNS == 0 and 0 < width // COLUMNS <= MAX_FRAMES,
            f'Expected a strip of 1..{MAX_FRAMES} frames of {COLUMNS} x {ROWS} pixels')
    result = []
    for frame in range(width // COLUMNS):
        bits = bytearray(FRAME_BYTES)
        for y in range(ROWS):
            for x in range(COLUMNS):
                r, g, b, a = rows[y][frame * COLUMNS + x]
                if a >= 128 and (r * 299 + g * 587 + b * 114) >= 128 * 1000:
                    dot = y * COLUMNS + x
                    bits[dot >> 3] |= 1 << (dot & 7)
        result.append(bytes(bits))
    return result


def header(strips):
    """C++ defining `const opxy::punch::Animation <name>` for each (name, PNG bytes)."""
    lines = ['// Generated by tooling/punch_animation.py; edit the PNG strips instead.',
             '#pragma once', '#include <opxy/punch.hpp>', '', 'namespace {']
    for name, data in strips:
        require(isinstance(name, str) and NAME.fullmatch(name), 'Animation name: lower-case identifier')
        parts = frames(data)
        for i, bits in enumerate(parts):
            values = ', '.join(f'0x{b:02x}' for b in bits)
            lines.append(f'const opxy::u8 {name}_frame{i}[{FRAME_BYTES}] = {{{values}}};')
        pointers = ', '.join(f'{name}_frame{i}' for i in range(len(parts)))
        lines += [f'const opxy::u8* const {name}_frames[] = {{{pointers}}};',
                  f'const opxy::punch::Animation {name}{{{name}_frames, 0, {len(parts)}}};']
    return '\n'.join(lines + ['}', ''])


def main(argv=None):
    parser = argparse.ArgumentParser(prog='python -m tooling.punch_animation', description=__doc__.splitlines()[0])
    parser.add_argument('strips', nargs='+', metavar='NAME=PNG',
                        help='C++ name and PNG with 40 x 18 frames side by side')
    args = parser.parse_args(argv)
    strips = []
    for item in args.strips:
        name, _, path = item.partition('=')
        require(path, 'Give each strip as NAME=PNG')
        strips.append((name, Path(path).read_bytes()))
    sys.stdout.buffer.write(header(strips).encode('ascii'))


if __name__ == '__main__':
    main()
