"""Build a module file (.opx, format 0, see sdk/platform/module_loader.hpp) from a module folder.

  python sdk.py module build <folder> --version 1.0.0 --out <file>.opx

The folder holds src/*.cpp; one unit exports extern "C" opxy_module_init.
Steps: compile with the pinned compiler, link at base 0 with relocations kept
(ld -q), turn the kept relocations into the .opx list (ABS32 / HI16 / LO16 with
target offsets; pc-relative ones need nothing), write manifest + image + relocs
+ trailer. Self-check: link again at another base and require that applying the
list to the base-0 image gives exactly that second image.
"""
import argparse
import json
from pathlib import Path
import re
import struct
import tempfile
import zlib

from .formats import elf_sections, require
from .pipeline import ROOT, execute, resolve_toolchain, tool_paths

LINKER = ROOT / 'linker/module.ld'
CHECK_BASE = 0x01234560  # aligned like the loader's bases (32)
MAGIC = b'OPXYMOD\0'
FORMAT = 0
TRAILER = struct.Struct('<9I2H8s')
OS_1_2_1 = 0x00010201
ABS32, HI16, LO16, IMPORT = 1, 2, 3, 4
IMPORT_PREFIX = 'opxy_import_'  # module.hpp: opxy::core calls through these
SLOTS = '''// Generated by the module builder: a slot for each firmware function the
// module imports by name. The loader writes each one's address at load.
extern "C" {{
{slots}
}}
'''
# binutils include/elf/bfin.h
R_BFIN_LUIMM16, R_BFIN_HUIMM16, R_BFIN_BYTE4_DATA = 0x06, 0x07, 0x12
PC_RELATIVE = {0x01, 0x03, 0x04, 0x08, 0x09, 0x0a, 0x0d, 0x0e, 0x13}
KINDS = {R_BFIN_BYTE4_DATA: ABS32, R_BFIN_HUIMM16: HI16, R_BFIN_LUIMM16: LO16}
LOADED = ('.text', '.rodata', '.data')
ENTRY = '_opxy_module_init'
MANIFEST = 1
NAME = re.compile(r'[A-Za-z0-9_-]{1,15}')  # the file name on the device, without .opx
# MAJOR.MINOR.PATCH, so a catalog can refuse an update that does not raise it.
VERSION = re.compile(r'(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)')


def api_version():
    """module_api_version, as sdk/include/opxy/module.hpp declares it."""
    text = (ROOT / 'sdk/include/opxy/module.hpp').read_text(encoding='utf-8')
    found = re.search(r'const u32 module_api_version = ([0-9]+);', text)
    require(found, 'module_api_version not found in module.hpp')
    return int(found.group(1))


def manifest(name, version, kind):
    """The module's manifest: what it is, for people and tools. The loader does
    not read it; see module_loader.hpp for what it may carry later."""
    require(NAME.fullmatch(name), f'Module name "{name}": letters, digits, _ and -, at most 15')
    require(type(version) is str and VERSION.fullmatch(version), f'Module version "{version}": MAJOR.MINOR.PATCH')
    return dict(manifest=MANIFEST, name=name, version=version, kind=kind, os='1.2.1', api=api_version())


def parse(data):
    """Sections, symbols and kept relocations of a linked module ELF."""
    headers = [h for _at, h in elf_sections(data)]
    names_index = struct.unpack_from('<H', data, 50)[0]

    def contents(h):
        return b'' if h[1] == 8 else data[h[4]:h[4] + h[5]]

    def string(table, index):
        return table[index:table.index(b'\0', index)].decode('ascii')

    names = contents(headers[names_index])
    sections = {string(names, h[0]): dict(type=h[1], flags=h[2], address=h[3], size=h[5], index=i)
                for i, h in enumerate(headers)}
    by_index = {s['index']: n for n, s in sections.items()}
    symbols, values = {}, []
    for h in headers:
        if h[1] != 2:
            continue
        strings = contents(headers[h[6]])
        table = contents(h)
        for pos in range(0, h[5], 16):
            index, value, _size, _info, _other, _section = struct.unpack_from('<IIIBBH', table, pos)
            values.append(value)
            if index:
                symbols[string(strings, index)] = value
    relocs = []
    for h in headers:
        if h[1] == 4:  # SHT_RELA
            target = by_index[h[7]]
            table = contents(h)
            for pos in range(0, h[5], 12):
                offset, info, addend = struct.unpack_from('<IIi', table, pos)
                relocs.append((target, offset, info & 0xff, values[info >> 8] + addend))
        else:
            require(h[1] != 9, 'REL relocations are not supported')
    return sections, symbols, relocs


def undefined_imports(objects):
    """The opxy_import_<name> symbols the objects use without defining them."""
    found = set()
    for path in objects:
        data = Path(path).read_bytes()
        headers = [h for _at, h in elf_sections(data)]
        for h in headers:
            if h[1] != 2:  # SHT_SYMTAB
                continue
            strings = data[headers[h[6]][4]:headers[h[6]][4] + headers[h[6]][5]]
            for pos in range(16, h[5], 16):
                index, _value, _size, _info, _other, section = struct.unpack_from('<IIIBBH', data, h[4] + pos)
                name = strings[index:strings.index(b'\0', index)].decode('ascii')
                if section == 0 and name.startswith(IMPORT_PREFIX):
                    found.add(name)
    return sorted(found)


def link_module(tools, cxx, work, objects):
    """Link at base 0 and check the relocation list against a second link; the
    imports get slots of their own. Returns image, bss, init, relocs and the
    names the imports refer to."""
    from . import native
    imports = undefined_imports(objects)
    if imports:
        source = work / 'imports.cpp'
        source.write_text(SLOTS.format(slots='\n'.join(
            f'void* {s} __asm__("{s}") __attribute__((section(".data"))) = 0;' for s in imports)),
            encoding='utf-8', newline='\n')
        objects = [*objects, native.compile_cxx(cxx, tools['as'], source.resolve(), work / 'imports.o', [])]
    image, bss, init, kept, symbols = link(tools, work, objects, 0)
    relocs = relocations(kept, image, 0)
    image1, bss1, init1, _, _ = link(tools, work, objects, CHECK_BASE)
    require((bss1, init1, len(image1)) == (bss, init, len(image)), 'Second link differs in layout')
    moved = apply(image, relocs, CHECK_BASE)
    if moved != image1:
        diff = [f'{i:#06x}: base0 {image[i]:02x} ours {moved[i]:02x} link {image1[i]:02x}'
                for i in range(len(image)) if moved[i] != image1[i]]
        raise ValueError('Relocation list does not reproduce the second link:\n  ' + '\n  '.join(diff[:20]))
    require(apply(image, relocs, 0) == image, 'Relocation list changes the base-0 image')
    names = b''
    for symbol in imports:
        offset = symbols[symbol]
        require(not offset & 3 and offset + 4 <= len(image), 'Import slot outside the image: ' + symbol)
        relocs.append((offset | IMPORT << 28, len(names)))
        names += symbol.removeprefix(IMPORT_PREFIX).encode('ascii') + b'\0'
    return image, bss, init, sorted(relocs), names


def link(tools, work, objects, base):
    elf = work / f'module-{base:08x}.elf'
    execute([tools['ld'], '-T', LINKER, f'--defsym=MODULE_BASE={base:#x}', '-q', '--gc-sections',
             '--no-undefined', *objects, '-o', elf])
    sections, symbols, relocs = parse(elf.read_bytes())
    allocated = {n for n, s in sections.items() if s['flags'] & 2 and s['size']}
    extra = allocated - set(LOADED) - {'.bss'}
    require(not extra, f'Unsupported sections: {sorted(extra)}')
    binary = work / f'image-{base:08x}.bin'
    execute([tools['objcopy'], '-O', 'binary', *[a for n in LOADED for a in ('-j', n)], elf, binary])
    image = binary.read_bytes()
    present = [n for n in LOADED if n in sections and sections[n]['size']]
    require(present and min(sections[n]['address'] for n in present) == base, 'Image does not start at the base')
    image += bytes(-len(image) % 4)
    bss = sections.get('.bss', dict(address=base + len(image), size=0))
    require(bss['size'] == 0 or bss['address'] == base + len(image), 'bss does not follow the image')
    require(ENTRY in symbols, 'opxy_module_init not found (extern "C")')
    return image, bss['size'], symbols[ENTRY] - base, relocs, {n: v - base for n, v in symbols.items()}


def relocations(relocs, image, base):
    """(where, target) pairs for a link at base; pc-relative ones need nothing."""
    out = []
    for section, offset, kind, value in relocs:
        if section not in LOADED or kind in PC_RELATIVE:
            continue
        require(kind in KINDS, f'Unsupported relocation type {kind:#x} at {offset:#x}')
        where = offset - base  # for HI16 / LO16 the offset is already the immediate half
        require(0 <= where < len(image), f'Relocation outside the image at {offset:#x}')
        out.append((where | KINDS[kind] << 28, (value - base) & 0xffffffff))
    return sorted(out)


def apply(image, relocs, base):
    image = bytearray(image)
    for where, target in relocs:
        offset, kind, value = where & 0x0fffffff, where >> 28, (base + target) & 0xffffffff
        if kind == ABS32:
            image[offset:offset + 4] = struct.pack('<I', value)
        else:
            image[offset:offset + 2] = struct.pack('<H', value >> 16 if kind == HI16 else value & 0xffff)
    return bytes(image)


def pack(manifest_, image, bss, init, relocs, names=b''):
    """Manifest JSON from offset 0, zero-padded to 4, then image, relocs, the
    import names, trailer."""
    text = (json.dumps(manifest_, indent=2) + '\n').encode('ascii')
    image_offset = len(text) + -len(text) % 4
    reloc_bytes = b''.join(struct.pack('<2I', w, t) for w, t in relocs)
    crc = zlib.crc32(names, zlib.crc32(reloc_bytes, zlib.crc32(image)))
    trailer = TRAILER.pack(len(text), image_offset, len(image), bss, image_offset + len(image), len(relocs), init, crc,
                           OS_1_2_1, FORMAT, TRAILER.size, MAGIC)
    require(TRAILER.size == 48, 'Trailer size')
    return text + bytes(image_offset - len(text)) + image + reloc_bytes + names + trailer


def inspect(data):
    """The loader's own checks, host side: trailer, layout, CRC and relocations;
    and the manifest, which the loader leaves alone."""
    require(len(data) >= TRAILER.size, 'Truncated module file')
    (manifest_bytes, image_offset, image_bytes, bss, reloc_offset, reloc_count, init, crc, os_version,
     format_, size, magic) = TRAILER.unpack(data[-TRAILER.size:])
    require(magic == MAGIC and format_ == FORMAT and size == TRAILER.size, 'Not a module file (format 0)')
    require(os_version == OS_1_2_1, 'Module built for another OS')
    end = len(data) - TRAILER.size
    require(not (image_offset | image_bytes) & 3 and image_bytes and image_offset + image_bytes <= end and
            manifest_bytes <= image_offset and
            reloc_offset + 8 * reloc_count <= end and init < image_bytes and not init & 1 and
            bss <= 0x01000000 and image_bytes <= 0x01000000, 'Module layout outside the file')
    image = data[image_offset:image_offset + image_bytes]
    relocs = data[reloc_offset:reloc_offset + 8 * reloc_count]
    names = data[reloc_offset + 8 * reloc_count:end]
    require(zlib.crc32(names, zlib.crc32(relocs, zlib.crc32(image))) == crc, 'Module checksum mismatch')
    imports = []
    for where, target in struct.iter_unpack('<2I', relocs):
        kind, offset = where >> 28, where & 0x0fffffff
        if kind == IMPORT:
            name_end = names.find(b'\0', target)
            require(not offset & 3 and offset + 4 <= image_bytes and target < name_end, 'Invalid module import')
            imports.append(names[target:name_end].decode('ascii', 'replace'))
            continue
        require(kind in (ABS32, HI16, LO16) and offset + (4 if kind == ABS32 else 2) <= image_bytes and
                target <= image_bytes + bss, 'Invalid module relocation')
    try:
        manifest_ = json.loads(data[:manifest_bytes]) if manifest_bytes else None
    except ValueError:
        manifest_ = None
    require(type(manifest_) is dict and manifest_.get('manifest') == MANIFEST, 'Module manifest missing or unreadable')
    return dict(manifest=manifest_, image=image_bytes, bss=bss, relocs=reloc_count, init=init, imports=sorted(imports))


def build(folder, out, version, toolchain=None, compiler=None):
    """A module folder: named after the folder, kind "module" (its own init, no
    machine around it)."""
    from . import native
    description = manifest(Path(folder).resolve().name, version, 'module')
    tool_dir, compiler_dir = resolve_toolchain(toolchain, compiler)
    tools = tool_paths(tool_dir)
    cxx = native.compiler_paths(compiler_dir)['cxx']
    sources = sorted((Path(folder) / 'src').glob('*.cpp'))
    require(sources, f'No src/*.cpp in {folder}')
    with tempfile.TemporaryDirectory(prefix='opxy-module-') as temp:
        work = Path(temp)
        objects = [native.compile_cxx(cxx, tools['as'], src.resolve(), work / (src.stem + '.o'),
                                      ['sdk/include', 'sdk/platform/blackfin/freestanding'])
                   for src in sources]
        image, bss, init, relocs, names = link_module(tools, cxx, work, objects)
    data = pack(description, image, bss, init, relocs, names)
    out = Path(out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_bytes(data)
    checked = inspect(data)
    return dict(file=str(out), manifest=checked['manifest'], imports=checked['imports'], bytes=len(data),
                image=len(image), bss=bss, relocs=len(relocs), init=hex(init),
                image_offset=len(data) - TRAILER.size - len(names) - 8 * len(relocs) - len(image))


MACHINE_INIT = '''// Generated by the module builder: {name} as a module. The machine's own
// code (core.h, engine.cpp, display.cpp) is compiled unchanged; this unit only
// wraps its callbacks and describes it for the firmware's synth_register,
// which it calls by name (opxy::core).
#include "core.h"
#include "engine.cpp"
#include "display_binding.hpp"
#include <opxy/module.hpp>
using opxy::u32;
using opxy::i32;
namespace {{
using Voice = {namespace}::Voice;
using Shared = {namespace}::Shared;
using opxy::binding::Frame;
using opxy::binding::DisplayState;
int handle = -1;
void initialize(void* v, void* s, u32 id) {{ {namespace}::initialize(*static_cast<Voice*>(v), *static_cast<Shared*>(s), id); }}
void start(void* v, void* s, u32 id) {{ {namespace}::start(*static_cast<Voice*>(v), *static_cast<Shared*>(s), id); }}
void destroy(void* v, void* s, u32 id) {{ {namespace}::destroy(*static_cast<Voice*>(v), *static_cast<Shared*>(s), id); }}
void render(void* v, void* s, u32 id, i32* out, const i32* controls, const u32* increments) {{
    {namespace}::render(*static_cast<Voice*>(v), *static_cast<Shared*>(s), id, out, controls, increments);
}}
void* factory(u32 index) {{ return handle < 0 ? nullptr : opxy::core::synth_voice(handle, index); }}
const char* const labels[] = {{{labels}}};
const char* parameter_name(u32 index) {{ return index < sizeof(labels) / sizeof(labels[0]) ? labels[index] : ""; }}
const char* const ids[] = {{{ids}}};
void display_reset(void* s, void* f) {{ {prefix}_display_reset(static_cast<DisplayState*>(s), static_cast<Frame*>(f)); }}
void display_render(void* s, const opxy::draw::Input* in, void* f) {{
    {prefix}_display_render(static_cast<DisplayState*>(s), in, static_cast<Frame*>(f));
}}
unsigned display_validate(const void* f) {{ return {prefix}_display_validate(static_cast<const Frame*>(f)); }}
// The page's artwork, exactly as a build would install it as content/display/{asset}.
const char svg[] = {{{svg}}};
const opxy::ModuleSynth synth = {{
    sizeof(opxy::ModuleSynth), "{name}", {engine_id}, {page_id}, factory, parameter_name,
    sizeof(Voice), alignof(Voice), {shared_bytes}, {capacity}, initialize, start, destroy, render,
    sizeof(DisplayState), alignof(DisplayState), sizeof(Frame),
    Frame::path_count, Frame::point_count, Frame::node_count, Frame::text_count, Frame::palette_count,
    __builtin_offsetof(Frame, nodes), __builtin_offsetof(Frame, texts), __builtin_offsetof(Frame, header),
    ids, "{asset}", display_reset, display_render, display_validate,
    svg, sizeof(svg), {catalog},
}};
static_assert(sizeof(ids) / sizeof(ids[0]) == Frame::node_count + Frame::text_count + Frame::palette_count,
              "Artwork IDs");
}}
extern "C" int opxy_module_init(const opxy::ModuleApi*) {{
    handle = opxy::core::synth_register(&synth);
    return handle < 0 ? 1 : 0;
}}
'''


def build_machine(folder, out, layout, version, toolchain=None, compiler=None):
    """A machine folder, unchanged, as a module: its sources, the generated
    display binding, a generated init that registers it, and the freestanding
    runtime. Its engine and page numbers come from the layout; the module is
    named after the machine's ID."""
    import json as _json
    from . import native
    from .adapters import generate_display
    from .machines import read_layout
    tool_dir, compiler_dir = resolve_toolchain(toolchain, compiler)
    tools = tool_paths(tool_dir)
    cxx = native.compiler_paths(compiler_dir)['cxx']
    _, machines, definitions = native.configuration([{'path': str(Path(folder).resolve())}], read_layout(Path(layout)))
    require(len(machines) == 1, 'One machine per module')
    m = machines[0]
    require(m.kind == 'synth', f'Only synths can be modules so far, not {m.kind}')
    require(m.display != 'stock', 'A synth module needs its own display')
    description = manifest(m.id, version, m.kind)
    from .adapters import catalog_entry
    ids = native.display_ids(m.prefix, m.definition['resources']['display'])
    artwork = native.screen.compose(native.validate_panel(m))
    entry = catalog_entry(m).strip().lstrip(',').strip()
    require(_json.loads(entry)['type'] == m.native_name and entry.isascii(), 'Unexpected catalog entry')
    values = dict(name=m.native_name, namespace=m.definition['id'], prefix=m.prefix,
                  engine_id=definitions[m.prefix + '_engine_id'], page_id=definitions[m.prefix + '_page_id'],
                  shared_bytes='sizeof(Shared)' if m.definition['resources']['sharedBytes'] else '0',
                  capacity=m.definition['resources']['voiceCapacity'],
                  labels=', '.join(_json.dumps(p['label'].lower()) for p in m.definition['parameters']),
                  # Its own name: never one a build installs, so module artwork shadows no file.
                  ids=', '.join(_json.dumps(i) for i in ids), asset='module-' + m.native_name + '.svg',
                  svg=', '.join(str(b) for b in artwork), catalog=_json.dumps(' '.join(entry.split())))
    with tempfile.TemporaryDirectory(prefix='opxy-machine-module-') as temp:
        work = Path(temp)
        generate_display(work, machine=m)
        (work / 'module_init.cpp').write_text(MACHINE_INIT.format(**values), encoding='utf-8', newline='\n')
        includes = [str(work), 'sdk/include', str(m.root), *[str(m.root / x) for x in m.includes],
                    'sdk/platform/blackfin/freestanding']
        sources = [work / 'module_init.cpp', work / 'display_binding.cpp', *[m.root / s for s in m.sources]]
        objects = [native.compile_cxx(cxx, tools['as'], src.resolve(), work / (src.stem + '.o'), includes)
                   for src in sources]
        objects.append(native.compile_cxx(cxx, tools['as'], (ROOT / native.RUNTIME_CXX).resolve(), work / 'memory.o',
                                          ['sdk/platform/blackfin/freestanding']))
        objects.append(work / 'divide.o')
        execute([tools['as'], '-mcpu=bf707', '-o', objects[-1], ROOT / native.RUNTIME_ASM])
        image, bss, init, relocs, names = link_module(tools, cxx, work, objects)
    data = pack(description, image, bss, init, relocs, names)
    out = Path(out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_bytes(data)
    checked = inspect(data)
    return dict(file=str(out), manifest=checked['manifest'], imports=checked['imports'], engine_id=values['engine_id'],
                page_id=values['page_id'], bytes=len(data), image=len(image), bss=bss, relocs=len(relocs))


def main(argv=None):
    parser = argparse.ArgumentParser(prog='sdk.py module', description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    commands = parser.add_subparsers(dest='command', required=True)
    command = commands.add_parser('build', help='Build a .opx module file from a module folder, or from a machine')
    command.add_argument('folder', type=Path, nargs='?')
    command.add_argument('--machine', type=Path, help='an unchanged machine folder, wrapped as a module')
    command.add_argument('--layout', type=Path, help="with --machine: the layout.json that numbers the machine")
    command.add_argument('--version', required=True,
                         help="the module's version, MAJOR.MINOR.PATCH; raise it with every release")
    command.add_argument('--out', type=Path, required=True)
    command.add_argument('--toolchain', type=Path)
    command.add_argument('--compiler', type=Path)
    args = parser.parse_args(argv)
    try:
        if args.machine:
            require(args.layout and not args.folder, '--machine needs --layout and no module folder')
            print(json.dumps(build_machine(args.machine, args.out, args.layout, args.version,
                                           args.toolchain, args.compiler), indent=2))
            return 0
        require(args.folder, 'A module folder or --machine')
        print(json.dumps(build(args.folder, args.out, args.version, args.toolchain, args.compiler), indent=2))
        return 0
    except (ValueError, OSError, KeyError) as error:
        parser.exit(1, str(error) + '\n')
